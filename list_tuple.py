numbers=input("Enter numbers separated using comma:").split(",")
numbers_tuple=tuple(numbers)
print("List:",numbers)
print("Tuple:",numbers_tuple)
print()
print("Number of elements in List:",len(numbers))
print("Number of elements in Tuple:",len(numbers_tuple))
print()
print("First element of List:",numbers[0])
print("Last element of List:",numbers[-1])
print()
print("First element of Tuple:",numbers_tuple[0])
print("Last element of Tuple:",numbers_tuple[-1])
print()
print("Reversing List:",numbers[::-1])

